# Core Round Step 1E: bake every action in the Blender source at 30 fps, verify the bake against the rig maths, add the
# mirrored clips, run QA on the BAKED data, and write
#   <anim>/export/CoreRoundAnim_Step1E.json        full-precision baked clips (local reference copy)
#   <anim>/export/qa_report.json                    QA results per clip
#   <repo>/src/.../CoreRound/AnimData.luau          compact Luau data module the client animation controller samples
#
#   "C:\Program Files\Blender Foundation\Blender 5.3\blender.exe" -b \
#       C:\WORLD.EXE-Art\CoreRound\animation\WorldEXE_CoreRound_Anim_Step1E.blend --python-exit-code 1 \
#       -P tools/animation/cr_anim_export.py
#
# Format: per clip, per joint, one quaternion (w, x, y, z) per frame (+ a translation for Root). Loops store frames
# 0..N-1 and wrap; one-shots store 0..N. Quaternions are the joints' Roblox Transform rotations directly (see the axis
# note in cr_anim_build.py), so the runtime builds CFrame.new(tx, ty, tz, qx, qy, qz, qw).
import hashlib
import json
import math
import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cr_anim_rig import JOINT_ORDER, fk, qnorm  # noqa: E402
import cr_anim_qa as QA  # noqa: E402
import cr_anim_clips as C  # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
ANIM = os.path.dirname(bpy.data.filepath)
EXPORT = os.path.join(ANIM, "export")
LUAU = os.path.join(REPO, "src", "StarterPlayer", "StarterPlayerScripts", "WORLD_EXE", "CoreRound", "AnimData.luau")


def bake(arm, act, meta):
    arm.animation_data.action = act
    if hasattr(arm.animation_data, "action_slot") and act.slots:
        arm.animation_data.action_slot = act.slots[0]
    sc = bpy.context.scene
    frames = []
    err = 0.0
    for f in range(meta["frames"] + 1):
        sc.frame_set(f)
        P = {}
        for j in JOINT_ORDER:
            pb = arm.pose.bones[j]
            q = qnorm(tuple(pb.rotation_quaternion))
            t = tuple(pb.location) if j == "Root" else (0.0, 0.0, 0.0)
            P[j] = (q, t)
        # verify: Blender's posed bone heads == the Roblox joint pivots computed by the rig maths
        _, piv = fk(P)
        for j in JOINT_ORDER:
            h = arm.pose.bones[j].head  # armature space (Blender)
            r = (h[0], h[2], -h[1])
            err = max(err, math.dist(r, piv[j]))
        frames.append(P)
    return frames, err


def mirror_frames(frames):
    return [C.mirror(P) for P in frames]


def r4(x):
    v = round(x, 4)
    return "0" if v == 0 else ("%.4f" % v).rstrip("0").rstrip(".")


def luau(clips):
    L = ["--!strict", "-- GENERATED by tools/animation/cr_anim_export.py from WorldEXE_CoreRound_Anim_Step1E.blend - do not edit",
         "-- by hand (edit the Blender source / cr_anim_clips.py and re-export). Core Round Step 1E original animation data:",
         "-- per clip, per joint, quaternions (w, x, y, z) per frame at 30 fps (+ Root translation). Loops store frames",
         "-- 0..N-1 and wrap; one-shots store 0..N. Values are the joints' Roblox Transforms (R15).",
         "return {", "\tfps = 30,", "\tclips = {"]
    for c in clips:
        m = c["meta"]
        L.append("\t\t%s = {" % m["name"])
        extra = ""
        if m.get("speed"):
            extra += ", speed = %s" % m["speed"]
        if m.get("mask"):
            extra += ", mask = { %s }" % ", ".join('"%s"' % x for x in m["mask"])
        L.append('\t\t\tloop = %s, frames = %d, layer = "%s"%s,' % (
            "true" if m.get("loop") else "false", m["frames"], m.get("layer", "full"), extra))
        L.append("\t\t\tj = {")
        n = m["frames"] if m.get("loop") else m["frames"] + 1
        joints = m.get("mask") or JOINT_ORDER
        for j in joints:
            qs = []
            for P in c["frames"][:n]:
                q = P[j][0]
                qs.extend(r4(v) for v in q)
            line = "\t\t\t\t%s = { q = { %s }" % (j, ", ".join(qs))
            if j == "Root":
                ts = []
                for P in c["frames"][:n]:
                    ts.extend(r4(v) for v in P[j][1])
                line += ", t = { %s }" % ", ".join(ts)
            L.append(line + " },")
        L.append("\t\t\t},")
        L.append("\t\t},")
    L.append("\t},")
    L.append("}")
    return "\n".join(L) + "\n"


def main():
    arm = bpy.data.objects["CR_R15"]
    out = []
    worst = 0.0
    for act in bpy.data.actions:
        if not act.name.startswith("CR_"):
            continue
        meta = json.loads(act["cr_meta"])
        frames, err = bake(arm, act, meta)
        worst = max(worst, err)
        out.append({"meta": meta, "frames": frames})
        if meta.get("mirror"):
            mm = dict(meta)
            mm["name"] = meta["mirror"]
            mm.pop("mirror")
            if "wall_x" in mm:
                mm["wall_x"] = mm["wall_x"]  # QA mirrors the frames back to check the wall on the right
            out.append({"meta": mm, "frames": mirror_frames(frames), "mirrored_from": meta["name"]})
    order = [c["name"] for c in C.all_clips()]
    out.sort(key=lambda c: (order.index(c["meta"]["name"]) if c["meta"]["name"] in order else
                            order.index(c["mirrored_from"]) + 0.5))
    # QA on the baked frames (mirrored clips are checked on their mirror image, which must equal the source)
    report = {"bake_vs_rig_max_err_studs": round(worst, 6), "clips": []}
    for c in out:
        fr = c["frames"] if "mirrored_from" not in c else mirror_frames(c["frames"])
        r = QA.qa_clip(c["meta"] if "mirrored_from" not in c else dict(c["meta"], name=c["mirrored_from"]), fr)
        r["name"] = c["meta"]["name"]
        report["clips"].append(r)
    os.makedirs(EXPORT, exist_ok=True)
    js = {"fps": 30, "source": os.path.basename(bpy.data.filepath),
          "clips": [{"meta": c["meta"], "frames": [{j: [list(P[j][0]), list(P[j][1])] for j in JOINT_ORDER}
                                                   for P in c["frames"]]} for c in out]}
    with open(os.path.join(EXPORT, "CoreRoundAnim_Step1E.json"), "w", encoding="utf-8") as fh:
        json.dump(js, fh)
    with open(os.path.join(EXPORT, "qa_report.json"), "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=1, default=str)
    src = luau(out)
    with open(LUAU, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src)
    print("CR_EXPORT clips", len(out), "bake_err", round(worst, 6), "luau_bytes", len(src.encode()),
          "sha256", hashlib.sha256(src.encode()).hexdigest()[:16])
    for r in report["clips"]:
        print("CR_QA", r["name"], "FAIL" if r["fails"] else "ok", r["fails"])


main()
